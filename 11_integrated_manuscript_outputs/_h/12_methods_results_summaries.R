## "never change with age" is the required wording, so the scan ignores it.
scan <- function(txt) {
    t <- gsub("never change with age", "", txt, fixed = TRUE)
    t <- gsub("forbidden: \"[^\"]*\"", "", t)
    hits <- BANNED[vapply(BANNED, function(b) any(grepl(b, t, fixed = TRUE)), logical(1))]
    if (length(hits)) stop("Banned framing in generated summary: ", paste(hits, collapse = ", "))
}
