## ------------------------------------------------------------------ helpers
## A key resolves only if the registry has the figure and, when panels are
## named, every one of them -- a summary may only cite what was rendered.
key <- function(fig, panel = NA_character_) {
    rows <- registry[registry$figure == fig]
    ok <- nrow(rows) > 0 && (all(is.na(panel)) || all(panel %in% rows$panel))
    if (!ok) stop("Registry has no entry for ", fig, ":",
                  paste(panel, collapse = ","),
                  " -- a summary sentence may only cite what was rendered.")
    sprintf("[%s%s]", fig, if (all(is.na(panel))) "" else
        paste0(":", paste(panel, collapse = ",")))
}
src <- function(fig, part) {
    f <- file.path(data_dir, paste0(fig, "_", part, ".tsv"))
    if (!file.exists(f)) stop("Missing source table ", basename(f))
    fread(f)
}
tbl_key <- function(name) {
    if (!file.exists(file.path(table_dir, name))) stop("Missing table ", name)
    sprintf("[tables/%s]", name)
}
num <- function(x, d = 2) formatC(as.numeric(x), digits = d, format = "f")
int <- function(x) formatC(as.numeric(x), format = "d", big.mark = ",")
pct <- function(x, d = 1) paste0(formatC(100 * as.numeric(x), digits = d, format = "f"), "%")
pv <- function(x) formatC(as.numeric(x), digits = 2, format = "g")
rlab <- function(r) unname(REGION_LABELS[as.character(r)] %||% as.character(r))
## "Caudate 0.40, DLPFC 0.33, Hippocampus 0.45" in REGION_ORDER.
per_region <- function(dt, value_fn, region_col = "region") {
    dt <- copy(dt)
    dt[, .reg := as.character(get(region_col))]
    dt[.reg %in% names(REGION_LABELS), .reg := REGION_LABELS[.reg]]
    dt <- dt[order(match(.reg, REGION_ORDER))]
    paste(sprintf("%s %s", dt$.reg, vapply(seq_len(nrow(dt)), function(i)
        value_fn(dt[i]), character(1))), collapse = ", ")
}
need_cfg <- function(cfg, path) {
    v <- cfg
    for (k in strsplit(path, ".", fixed = TRUE)[[1]]) {
        v <- v[[k]]
        if (is.null(v)) stop("Config key missing: ", path)
    }
    v
}
decision_of <- function(mod) {
    d <- unique(claims$decision[claims$module == mod & claims$gating %in% c(TRUE, "TRUE")])
    paste(d[!is.na(d)], collapse = " / ")
}

