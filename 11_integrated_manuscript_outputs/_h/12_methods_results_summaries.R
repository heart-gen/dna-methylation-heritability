#### 11 / Manuscript-ready Methods and Results summaries ####
##
## AGENTS.md 7.11 names "manuscript-ready Methods and Results summaries" among
## this module's products. They are written here, last before the seal, as
##
##   tables/results-summary.md   Results in AGENTS.md 11 order, plus the
##                               supplementary analyses
##   tables/methods-summary.md   locked parameters, inference and run IDs
##
## They are summaries for the writer, not manuscript prose. Three rules make
## them safe to write from:
##
##   * No sentence carries a hand-typed number. Every number is read from a
##     source-data table this run rendered, and the sentence cites that table's
##     registry key as [figure:panel], which resolves in
##     manuscript-number-registry.tsv (= Supplementary Data 14). A key that is
##     not in the registry stops the build.
##   * Claim wording is not composed here. Where a module emits its permitted
##     claim or decision token, that string is quoted verbatim.
##   * The output is scanned for withdrawn metrics and for framing AGENTS.md
##     2.3, 3, 7.8 and 7.10 forbid. A hit stops the build.
##
## Usage:
##   Rscript 12_methods_results_summaries.R --cohort AA --run-id fig-all-YYYYMMDD

